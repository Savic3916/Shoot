// Builds src/constants/leagues.ts: ESPN soccer league id -> [name, country/region].
// Usage: node scripts/make-league-map.mjs
import { writeFileSync } from 'node:fs';

const list = await (await fetch('https://sports.core.api.espn.com/v2/sports/soccer/leagues?limit=1000')).json();
const refs = list.items.map((item) => item.$ref.replace('http://', 'https://'));
const map = {};
let next = 0;
async function worker() {
  while (next < refs.length) {
    const ref = refs[next++];
    try {
      const league = await (await fetch(ref)).json();
      const country = typeof league.country === 'object' ? (league.country?.name ?? league.country?.abbreviation ?? '') : String(league.country ?? '');
      map[league.id] = [league.name, country, league.slug];
    } catch {
      console.error('failed', ref);
    }
  }
}
await Promise.all(Array.from({ length: 8 }, worker));
const body = Object.entries(map)
  .sort((a, b) => Number(a[0]) - Number(b[0]))
  .map(([id, [name, country, slug]]) => `  '${id}': [${JSON.stringify(name)}, ${JSON.stringify(country)}, ${JSON.stringify(slug)}],`)
  .join('\n');
writeFileSync('src/constants/leagues.ts', `// Generated by scripts/make-league-map.mjs. ESPN soccer league id -> [name, country, slug].\nexport const LEAGUES: Record<string, [string, string, string]> = {\n${body}\n};\n`);
console.log('leagues', Object.keys(map).length);
